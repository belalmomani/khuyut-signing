/** يولّد ألغازًا ثابتة (نفس الترتيب في كل تشغيل): لكل مستوى فئة من عائلة مختلفة، وأربع كلمات منها. */
object Generator {
    fun generate(count: Int): List<Puzzle> {
        val out = mutableListOf<Puzzle>()
        val seen = HashSet<String>()
        var seed = 7L
        var guard = 0
        while (out.size < count && guard < count * 50) {
            guard++
            val p = make(seed++) ?: continue
            val key = p.groups.map { it.title }.sorted().joinToString("|") + "#" +
                p.allWords.sorted().joinToString(",")
            if (seen.add(key)) out.add(p)
        }
        return out
    }

    private fun make(seed: Long): Puzzle? {
        val rnd = Random(seed)
        val usedFamilies = HashSet<String>()
        val groups = ArrayList<Group>()
        for (level in 0..3) {
            val options = Bank.categories.filter { it.level == level && it.family !in usedFamilies }
            if (options.isEmpty()) return null
            val cat = options[rnd.nextInt(options.size)]
            usedFamilies.add(cat.family)
            groups.add(Group(cat.title, cat.words.shuffled(rnd).take(4), level))
        }
        if (groups.flatMap { it.words }.toSet().size != 16) return null
        return Puzzle(groups)
    }
}
